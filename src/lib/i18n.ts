const dicts: Record<Lang, Dict> = { vi, en };

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const lookup = dicts[lang] ?? dicts.vi;
  let str = lookup[key] ?? dicts.vi[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

export function useT() {
  const lang = useAppStore((s) => s.settings?.ui_language ?? ("vi" as Lang));
  return useCallback(
    (key: string, vars?: Vars) => translate(lang, key, vars),
    [lang],
  );
}
